BEGIN;

CREATE TABLE IF NOT EXISTS public.agendas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS public.bancos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  ccorrente text,
  agencia text,
  chave_pix text,
  pessoa_id bigint NOT NULL,
  status text NOT NULL DEFAULT 'ativo'
);

CREATE TABLE IF NOT EXISTS public.checklists (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo text NOT NULL,
  status text NOT NULL,
  descricao text,
  tipo text NOT NULL DEFAULT 'personalizado'
);

ALTER TABLE public.checklists
  ADD COLUMN IF NOT EXISTS tipo text NOT NULL DEFAULT 'personalizado';

CREATE TABLE IF NOT EXISTS public.checklist_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  checklist_id bigint NOT NULL,
  titulo text NOT NULL,
  posicao smallint NOT NULL DEFAULT 0,
  descricao text,
  regra text
);

CREATE TABLE IF NOT EXISTS public.equipamentos (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  nome text,
  descricao text,
  observacao text,
  imovel_id bigint NOT NULL,
  PRIMARY KEY (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_equipamentos_id_imovel_unique
  ON public.equipamentos (id, imovel_id);

CREATE TABLE IF NOT EXISTS public.imoveis (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text,
  endereco text,
  cep text,
  cidade text,
  estado text,
  image_data bytea,
  image_mime_type text
);

ALTER TABLE public.imoveis
  ADD COLUMN IF NOT EXISTS image_data bytea,
  ADD COLUMN IF NOT EXISTS image_mime_type text;

CREATE TABLE IF NOT EXISTS public.equipamentos_fotos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  equipamento_id bigint NOT NULL,
  imovel_id bigint NOT NULL,
  image_data bytea NOT NULL,
  image_mime_type text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (equipamento_id, imovel_id)
    REFERENCES public.equipamentos(id, imovel_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.prepostos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  email text,
  telefone text,
  cpf_cnpj text,
  endereco text,
  cidade text,
  estado text,
  tipo text,
  status text
);

CREATE TABLE IF NOT EXISTS public.prestadores_servico (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text,
  email text,
  telefone text,
  cpf_cnpj text,
  endereco text,
  cidade text,
  estado text
);

CREATE TABLE IF NOT EXISTS public.proprietarios_adm (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  email text,
  telefone text,
  cpf_cnpj text,
  endereco text,
  cidade text,
  estado text
);

CREATE TABLE IF NOT EXISTS public.proprietarios_adm_imoveis (
  proprietarios_adm_id bigint NOT NULL REFERENCES public.proprietarios_adm(id) ON DELETE CASCADE,
  imoveis_id bigint NOT NULL REFERENCES public.imoveis(id) ON DELETE CASCADE,
  PRIMARY KEY (proprietarios_adm_id, imoveis_id)
);

CREATE TABLE IF NOT EXISTS public.tarefas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  descricao text,
  dt_inicio timestamptz,
  dt_fim timetz,
  status text
);

CREATE TABLE IF NOT EXISTS public.usuarios (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  email text NOT NULL,
  password_hash text NOT NULL,
  dt_criacao timestamptz NOT NULL DEFAULT now(),
  dt_alteracao timestamptz NOT NULL DEFAULT now(),
  pessoa_id bigint,
  tipo_pessoa text
);

ALTER TABLE public.usuarios
  ADD COLUMN IF NOT EXISTS must_change_password boolean NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS public.tarefas_operacao (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  imovel_id bigint NOT NULL REFERENCES public.imoveis(id) ON DELETE CASCADE,
  nome text NOT NULL,
  observacao text,
  dt_inicio timestamptz,
  dt_fim timestamptz,
  executor_tipo text NOT NULL CHECK (executor_tipo IN ('administrator', 'provider')),
  executor_administrador_id bigint REFERENCES public.proprietarios_adm(id) ON DELETE RESTRICT,
  executor_prestador_id bigint REFERENCES public.prestadores_servico(id) ON DELETE RESTRICT,
  status text NOT NULL DEFAULT 'iniciar'
    CHECK (status IN ('iniciar', 'em_andamento', 'final_ok', 'final_prb', 'cancelada')),
  created_by_user_id bigint NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  CHECK (
    (executor_tipo = 'administrator' AND executor_administrador_id IS NOT NULL
      AND executor_prestador_id IS NULL)
    OR
    (executor_tipo = 'provider' AND executor_prestador_id IS NOT NULL
      AND executor_administrador_id IS NULL)
  ),
  CHECK (dt_inicio IS NULL OR dt_fim IS NULL OR dt_inicio <= dt_fim)
);

ALTER TABLE public.tarefas_operacao
  ADD COLUMN IF NOT EXISTS provider_started boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS observacao_prestador text;

CREATE TABLE IF NOT EXISTS public.tarefas_operacao_imagens (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tarefa_id bigint NOT NULL
    REFERENCES public.tarefas_operacao(id) ON DELETE CASCADE,
  uploaded_by_user_id bigint NOT NULL
    REFERENCES public.usuarios(id) ON DELETE CASCADE,
  image_data bytea NOT NULL,
  image_mime_type text NOT NULL
    CHECK (image_mime_type IN ('image/jpeg', 'image/png', 'image/webp')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_tarefas_operacao_imagens_task
  ON public.tarefas_operacao_imagens (tarefa_id, created_at DESC);

CREATE TABLE IF NOT EXISTS public.tarefas_operacao_mensagens (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tarefa_id bigint NOT NULL
    REFERENCES public.tarefas_operacao(id) ON DELETE CASCADE,
  sender_user_id bigint REFERENCES public.usuarios(id) ON DELETE SET NULL,
  sender_name text NOT NULL,
  sender_type text NOT NULL
    CHECK (sender_type IN ('proprietario_adm', 'prestador_servico')),
  mensagem text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_tarefas_operacao_mensagens_task
  ON public.tarefas_operacao_mensagens (tarefa_id, created_at, id);

CREATE INDEX IF NOT EXISTS idx_tarefas_operacao_owner_dates
  ON public.tarefas_operacao (created_by_user_id, dt_inicio);

CREATE INDEX IF NOT EXISTS idx_tarefas_operacao_property
  ON public.tarefas_operacao (imovel_id);

CREATE TABLE IF NOT EXISTS public.tarefas_operacao_checklists (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tarefa_id bigint NOT NULL
    REFERENCES public.tarefas_operacao(id) ON DELETE CASCADE,
  checklist_origem_id bigint NOT NULL,
  titulo text NOT NULL,
  posicao smallint NOT NULL DEFAULT 0,
  UNIQUE (tarefa_id, checklist_origem_id)
);

CREATE TABLE IF NOT EXISTS public.tarefas_operacao_checklist_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tarefa_checklist_id bigint NOT NULL
    REFERENCES public.tarefas_operacao_checklists(id) ON DELETE CASCADE,
  titulo text NOT NULL,
  descricao text,
  regra text,
  posicao smallint NOT NULL DEFAULT 0,
  concluido boolean NOT NULL DEFAULT false
);

ALTER TABLE public.usuarios
  ALTER COLUMN pessoa_id DROP NOT NULL;

ALTER TABLE public.checklists
  ADD COLUMN IF NOT EXISTS created_by_user_id bigint
  REFERENCES public.usuarios(id) ON DELETE CASCADE;

ALTER TABLE public.checklists
  ADD COLUMN IF NOT EXISTS modelo_padrao_id bigint
  REFERENCES public.checklists(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_checklists_owner_type
  ON public.checklists (created_by_user_id, tipo);

CREATE INDEX IF NOT EXISTS idx_checklists_template_source
  ON public.checklists (modelo_padrao_id);

CREATE UNIQUE INDEX IF NOT EXISTS idx_checklists_unique_owner_template
  ON public.checklists (created_by_user_id, modelo_padrao_id)
  WHERE modelo_padrao_id IS NOT NULL;

ALTER TABLE public.proprietarios_adm
  ADD COLUMN IF NOT EXISTS endereco text,
  ADD COLUMN IF NOT EXISTS cidade text,
  ADD COLUMN IF NOT EXISTS estado text,
  ADD COLUMN IF NOT EXISTS created_by_user_id bigint
  REFERENCES public.usuarios(id) ON DELETE CASCADE;

ALTER TABLE public.prepostos
  ADD COLUMN IF NOT EXISTS endereco text,
  ADD COLUMN IF NOT EXISTS cidade text,
  ADD COLUMN IF NOT EXISTS estado text,
  ADD COLUMN IF NOT EXISTS created_by_user_id bigint
  REFERENCES public.usuarios(id) ON DELETE CASCADE;

ALTER TABLE public.prestadores_servico
  ADD COLUMN IF NOT EXISTS endereco text,
  ADD COLUMN IF NOT EXISTS cidade text,
  ADD COLUMN IF NOT EXISTS estado text,
  ADD COLUMN IF NOT EXISTS created_by_user_id bigint
  REFERENCES public.usuarios(id) ON DELETE CASCADE;

ALTER TABLE public.proprietarios_adm
  ADD COLUMN IF NOT EXISTS archived_at timestamptz;

ALTER TABLE public.prepostos
  ADD COLUMN IF NOT EXISTS archived_at timestamptz;

ALTER TABLE public.prestadores_servico
  ADD COLUMN IF NOT EXISTS archived_at timestamptz,
  ADD COLUMN IF NOT EXISTS codigo_pix text;

CREATE INDEX IF NOT EXISTS idx_proprietarios_adm_created_by_user_id
  ON public.proprietarios_adm (created_by_user_id);

CREATE INDEX IF NOT EXISTS idx_prepostos_created_by_user_id
  ON public.prepostos (created_by_user_id);

CREATE INDEX IF NOT EXISTS idx_prestadores_servico_created_by_user_id
  ON public.prestadores_servico (created_by_user_id);

UPDATE public.proprietarios_adm pa
SET created_by_user_id = u.id
FROM public.usuarios u
WHERE u.pessoa_id = pa.id
  AND u.tipo_pessoa = 'proprietario_adm'
  AND pa.created_by_user_id IS NULL;

COMMIT;
