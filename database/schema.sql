BEGIN;

CREATE TABLE IF NOT EXISTS public.agendas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS public.bancos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  ccorrente text,
  agencia text,
  chave_pix text,
  pessoa_id bigint NOT NULL,
  status text NOT NULL DEFAULT 'ativo'
);

CREATE TABLE IF NOT EXISTS public.checklists (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  titulo text NOT NULL,
  status text NOT NULL,
  descricao text
);

CREATE TABLE IF NOT EXISTS public.checklist_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  checklist_id bigint NOT NULL,
  titulo text NOT NULL,
  posicao smallint NOT NULL DEFAULT 0,
  descricao text,
  regra text
);

CREATE TABLE IF NOT EXISTS public.equipamentos (
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  nome text,
  descricao text,
  observacao text,
  imovel_id bigint NOT NULL,
  PRIMARY KEY (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_equipamentos_id_imovel_unique
  ON public.equipamentos (id, imovel_id);

CREATE TABLE IF NOT EXISTS public.imoveis (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text,
  endereco text,
  cep text,
  cidade text,
  estado text,
  image_data bytea,
  image_mime_type text
);

ALTER TABLE public.imoveis
  ADD COLUMN IF NOT EXISTS image_data bytea,
  ADD COLUMN IF NOT EXISTS image_mime_type text;

CREATE TABLE IF NOT EXISTS public.equipamentos_fotos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  equipamento_id bigint NOT NULL,
  imovel_id bigint NOT NULL,
  image_data bytea NOT NULL,
  image_mime_type text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (equipamento_id, imovel_id)
    REFERENCES public.equipamentos(id, imovel_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.prepostos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  email text,
  telefone text,
  cpf_cnpj text,
  tipo text,
  status text
);

CREATE TABLE IF NOT EXISTS public.prestadores_servico (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text,
  email text,
  telefone text,
  cpf_cnpj text
);

CREATE TABLE IF NOT EXISTS public.proprietarios_adm (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  email text,
  telefone text,
  cpf_cnpj text
);

CREATE TABLE IF NOT EXISTS public.proprietarios_adm_imoveis (
  proprietarios_adm_id bigint NOT NULL REFERENCES public.proprietarios_adm(id) ON DELETE CASCADE,
  imoveis_id bigint NOT NULL REFERENCES public.imoveis(id) ON DELETE CASCADE,
  PRIMARY KEY (proprietarios_adm_id, imoveis_id)
);

CREATE TABLE IF NOT EXISTS public.tarefas (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  descricao text,
  dt_inicio timestamptz,
  dt_fim timetz,
  status text
);

CREATE TABLE IF NOT EXISTS public.usuarios (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome text NOT NULL,
  email text NOT NULL,
  password_hash text NOT NULL,
  dt_criacao timestamptz NOT NULL DEFAULT now(),
  dt_alteracao timestamptz NOT NULL DEFAULT now(),
  pessoa_id bigint,
  tipo_pessoa text
);

ALTER TABLE public.usuarios
  ALTER COLUMN pessoa_id DROP NOT NULL;

ALTER TABLE public.proprietarios_adm
  ADD COLUMN IF NOT EXISTS created_by_user_id bigint
  REFERENCES public.usuarios(id) ON DELETE CASCADE;

ALTER TABLE public.prepostos
  ADD COLUMN IF NOT EXISTS created_by_user_id bigint
  REFERENCES public.usuarios(id) ON DELETE CASCADE;

ALTER TABLE public.prestadores_servico
  ADD COLUMN IF NOT EXISTS created_by_user_id bigint
  REFERENCES public.usuarios(id) ON DELETE CASCADE;

CREATE INDEX IF NOT EXISTS idx_proprietarios_adm_created_by_user_id
  ON public.proprietarios_adm (created_by_user_id);

CREATE INDEX IF NOT EXISTS idx_prepostos_created_by_user_id
  ON public.prepostos (created_by_user_id);

CREATE INDEX IF NOT EXISTS idx_prestadores_servico_created_by_user_id
  ON public.prestadores_servico (created_by_user_id);

UPDATE public.proprietarios_adm pa
SET created_by_user_id = u.id
FROM public.usuarios u
WHERE u.pessoa_id = pa.id
  AND u.tipo_pessoa = 'proprietario_adm'
  AND pa.created_by_user_id IS NULL;

COMMIT;
